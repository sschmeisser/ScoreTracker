#!/usr/bin/env python3
"""
generate_boot_header.py - Export the ScoreTracker emblem as an 80x80 RGB565 array
with 0xF81F chroma-key transparency.
"""

import os
import sys
from PIL import Image

sys.path.append(os.path.dirname(os.path.abspath(__file__)))
from design_startup_logo import create_emblem

PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_HEADER = os.path.join(PROJECT_DIR, "cheap-yellow-display", "src", "boot_logo.h")

CHROMA_KEY = 0xF81F
CARD_BG = (22, 33, 27)  # #16211B

def to_rgb565(r, g, b):
    r5 = (r >> 3) & 0x1F
    g6 = (g >> 2) & 0x3F
    b5 = (b >> 3) & 0x1F
    return (r5 << 11) | (g6 << 5) | b5

def main():
    size = 80
    emblem = create_emblem(size)  # RGBA image

    pixels = []
    for y in range(size):
        for x in range(size):
            r, g, b, a = emblem.getpixel((x, y))
            if a < 32:
                pixels.append(CHROMA_KEY)
            else:
                # Composite slightly over card background if semi-transparent
                br = (r * a + CARD_BG[0] * (255 - a)) // 255
                bg = (g * a + CARD_BG[1] * (255 - a)) // 255
                bb = (b * a + CARD_BG[2] * (255 - a)) // 255
                val = to_rgb565(br, bg, bb)
                if val == CHROMA_KEY:
                    val = 0xF81E
                pixels.append(val)

    with open(OUT_HEADER, "w") as f:
        f.write("// Autogenerated ScoreTracker Emblem (80x80 RGB565 with 0xF81F Chroma-Key)\n")
        f.write("#pragma once\n\n")
        f.write("#include <Arduino.h>\n\n")
        f.write(f"#define EMBLEM_SIZE {size}\n\n")
        f.write(f"static const uint16_t SCORETRACKER_EMBLEM_80x80[{size} * {size}] PROGMEM = {{\n")
        for i, val in enumerate(pixels):
            if i % 16 == 0:
                f.write("  ")
            f.write(f"0x{val:04X}, ")
            if i % 16 == 15:
                f.write("\n")
        f.write("};\n")

    print(f"Generated {OUT_HEADER} ({os.path.getsize(OUT_HEADER)} bytes)")

if __name__ == "__main__":
    main()
