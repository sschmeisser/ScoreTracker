import os
from PIL import Image

TEAMS = [
    'ARI', 'ATL', 'BAL', 'BUF',
    'CAR', 'CHI', 'CIN', 'CLE',
    'DAL', 'DEN', 'DET', 'GB',
    'HOU', 'IND', 'JAX', 'KC',
    'LAC', 'LAR', 'LV',  'MIA',
    'MIN', 'NE',  'NO',  'NYG',
    'NYJ', 'PHI', 'PIT', 'SEA',
    'SF',  'TB',  'TEN', 'WAS'
]

LOGO_W = 32
LOGO_H = 26
CHROMA_KEY = 0xF81F  # Neon Magenta transparent key

CARD_BG = (22, 32, 27)      # 0x1103 Deep Forest Moss
SCREEN_BG = (22, 32, 27)    # 0x1103 Deep Forest Moss

def to_rgb565(r, g, b):
    r5 = (r >> 3) & 0x1F
    g6 = (g >> 2) & 0x3F
    b5 = (b >> 3) & 0x1F
    return (r5 << 11) | (g6 << 5) | b5

def process_image(path, target_w, target_h, bg_color):
    im = Image.open(path).convert('RGBA')
    bbox = im.getbbox()
    if bbox:
        im = im.crop(bbox)
    w, h = im.size
    scale = min(target_w / w, target_h / h)
    nw, nh = max(1, int(w * scale)), max(1, int(h * scale))
    im_resized = im.resize((nw, nh), Image.Resampling.LANCZOS)

    canvas = Image.new('RGBA', (target_w, target_h), (0, 0, 0, 0))
    ox = (target_w - nw) // 2
    oy = (target_h - nh) // 2
    canvas.paste(im_resized, (ox, oy), im_resized)

    pixels_565 = []
    for y in range(target_h):
        for x in range(target_w):
            r, g, b, a = canvas.getpixel((x, y))
            if a < 16:
                pixels_565.append(CHROMA_KEY)
            else:
                br = (r * a + bg_color[0] * (255 - a)) // 255
                bg = (g * a + bg_color[1] * (255 - a)) // 255
                bb = (b * a + bg_color[2] * (255 - a)) // 255
                val = to_rgb565(br, bg, bb)
                if val == CHROMA_KEY:
                    val = 0xF81E
                pixels_565.append(val)
    return pixels_565

out_path = 'src/nfl_logos.h'
with open(out_path, 'w') as f:
    f.write('// Autogenerated Official NFL Logos for ESP32 (RGB565 with 0xF81F chroma-key)\n')
    f.write('#pragma once\n\n')
    f.write('#include <Arduino.h>\n\n')
    f.write(f'#define NFL_LOGO_WIDTH {LOGO_W}\n')
    f.write(f'#define NFL_LOGO_HEIGHT {LOGO_H}\n')
    f.write(f'#define NFL_LOGO_CHROMA_KEY 0x{CHROMA_KEY:04X}\n\n')
    
    # NFL Shield
    f.write('#define NFL_SHIELD_WIDTH 16\n')
    f.write('#define NFL_SHIELD_HEIGHT 18\n')
    shield_data = process_image('tools/logos_cache/NFL.png', 16, 18, SCREEN_BG)
    f.write('static const uint16_t NFL_SHIELD_DATA[16 * 18] PROGMEM = {\n')
    for i, p in enumerate(shield_data):
        if i % 16 == 0:
            f.write('  ')
        f.write(f'0x{p:04X}, ')
        if i % 16 == 15:
            f.write('\n')
    f.write('};\n\n')

    # Team Logos
    for t in TEAMS:
        path = f'tools/logos_cache/{t}.png'
        data = process_image(path, LOGO_W, LOGO_H, CARD_BG)
        f.write(f'static const uint16_t NFL_LOGO_{t}[{LOGO_W} * {LOGO_H}] PROGMEM = {{\n')
        for i, p in enumerate(data):
            if i % 16 == 0:
                f.write('  ')
            f.write(f'0x{p:04X}, ')
            if i % 16 == 15:
                f.write('\n')
        f.write('};\n\n')

    f.write('struct NFLLogoEntry {\n')
    f.write('  const char* code;\n')
    f.write('  const uint16_t* data;\n')
    f.write('};\n\n')
    
    f.write('static const NFLLogoEntry NFL_ALL_LOGOS[] = {\n')
    for t in TEAMS:
        f.write(f'  {{ "{t}", NFL_LOGO_{t} }},\n')
    f.write('  { "WSH", NFL_LOGO_WAS },\n') # Alias
    f.write('};\n\n')

    f.write('inline const uint16_t* get_nfl_team_logo_bitmap(const char* code) {\n')
    f.write('  for (size_t i = 0; i < sizeof(NFL_ALL_LOGOS) / sizeof(NFL_ALL_LOGOS[0]); ++i) {\n')
    f.write('    if (strcmp(NFL_ALL_LOGOS[i].code, code) == 0) return NFL_ALL_LOGOS[i].data;\n')
    f.write('  }\n')
    f.write('  return nullptr;\n')
    f.write('}\n')

print(f'Generated {out_path}, size: {os.path.getsize(out_path)} bytes')
